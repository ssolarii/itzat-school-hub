-- Itz'at school publishing API. Run on the separate school project.
-- Published documents contain only deliberately public school information.
begin;

create table if not exists public.school_versions (
  revision bigint primary key generated by default as identity,
  document jsonb not null,
  published_at timestamptz not null default now(),
  published_by uuid references auth.users(id) on delete set null
);
create table if not exists public.school_members (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('developer','principal','teacher','codeveloper')),
  capabilities text[] not null default '{}',
  groups text[] not null default '{}',
  active boolean not null default true,
  updated_at timestamptz not null default now()
);
create table if not exists public.school_notice_drafts (
  id uuid primary key default gen_random_uuid(),
  submitted_by uuid not null references auth.users(id) on delete cascade,
  notice jsonb not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id) on delete set null
);
create table if not exists public.school_audit_events (
  id bigint primary key generated by default as identity,
  actor uuid references auth.users(id) on delete set null,
  action text not null,
  details jsonb not null default '{}',
  occurred_at timestamptz not null default now()
);
alter table public.school_versions enable row level security;
alter table public.school_members enable row level security;
alter table public.school_notice_drafts enable row level security;
alter table public.school_audit_events enable row level security;

-- Internal helpers are deliberately outside the exposed public schema.
create schema if not exists school_private;
revoke all on schema school_private from public, anon, authenticated;
grant usage on schema school_private to authenticated;

create or replace function school_private.has_capability(p_capability text)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.school_members m where m.user_id = auth.uid()
    and m.active and (m.role in ('developer','principal') or p_capability = any(m.capabilities)));
$$;
create or replace function school_private.in_scope(p_group text)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.school_members m where m.user_id = auth.uid()
    and m.active and (m.role in ('developer','principal') or '*' = any(m.groups) or p_group = any(m.groups)));
$$;
create or replace function school_private.is_leadership()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.school_members m where m.user_id = auth.uid()
    and m.active and m.role in ('developer','principal'));
$$;
revoke all on function school_private.has_capability(text), school_private.in_scope(text), school_private.is_leadership() from public, anon, authenticated;
grant execute on function school_private.has_capability(text), school_private.in_scope(text), school_private.is_leadership() to authenticated;

drop policy if exists school_public_read on public.school_versions;
create policy school_public_read on public.school_versions for select to anon, authenticated using (true);
drop policy if exists school_own_membership on public.school_members;
create policy school_own_membership on public.school_members for select to authenticated using (user_id = (select auth.uid()) or (select school_private.is_leadership()));
drop policy if exists school_notice_review_read on public.school_notice_drafts;
create policy school_notice_review_read on public.school_notice_drafts for select to authenticated using (
  submitted_by = (select auth.uid()) or
  (school_private.has_capability('notices.publish') and school_private.in_scope(notice->>'audience')));
drop policy if exists school_audit_read on public.school_audit_events;
create policy school_audit_read on public.school_audit_events for select to authenticated using ((select school_private.is_leadership()));
revoke all on public.school_versions, public.school_members, public.school_notice_drafts, public.school_audit_events from anon, authenticated;
-- Do not expose publisher auth UUIDs in the public projection.
grant select(revision, document, published_at) on public.school_versions to anon, authenticated;
grant select on public.school_members, public.school_notice_drafts, public.school_audit_events to authenticated;

create or replace function school_private.assert_keys(p_object jsonb, p_allowed text[], p_label text)
returns void language plpgsql immutable set search_path = '' as $$
begin
  if jsonb_typeof(p_object) is distinct from 'object' or exists(select 1 from jsonb_object_keys(p_object) k where not k = any(p_allowed)) then
    raise exception '% has invalid or unknown fields', p_label using errcode = '22023';
  end if;
end; $$;

create or replace function school_private.validate_notice(p_notice jsonb, p_groups jsonb)
returns void language plpgsql immutable set search_path = '' as $$
begin
  perform school_private.assert_keys(p_notice, array['id','title','body','audience','subject','publishedAt','expiresAt','approved'], 'Notice');
  if coalesce(length(p_notice->>'id'),0) = 0 or coalesce(length(trim(p_notice->>'title')),0) not between 1 and 160 or
    coalesce(length(trim(p_notice->>'body')),0) not between 1 and 10000 or
    not coalesce((p_notice->>'audience' = 'school' or p_groups ? (p_notice->>'audience')),false) or
    p_notice->'approved' is distinct from 'true'::jsonb or p_notice->>'publishedAt' is null then
    raise exception 'Notice requires ID, title, body, valid audience, approval and publication time' using errcode = '22023';
  end if;
  perform (p_notice->>'publishedAt')::timestamptz;
  if p_notice->>'expiresAt' is not null and (p_notice->>'expiresAt')::timestamptz <= (p_notice->>'publishedAt')::timestamptz then
    raise exception 'Notice expiry must follow publication' using errcode = '22023';
  end if;
end; $$;

create or replace function school_private.validate_school_document(p_document jsonb)
returns void language plpgsql immutable set search_path = '' as $$
declare
  v_group record; v_day jsonb; v_lesson jsonb; v_profile record; v_slot jsonb; v_calendar record; v_item jsonb;
  v_index integer; v_span integer; v_slots integer; v_previous text; v_date date;
begin
  perform school_private.assert_keys(p_document,array['settings','groups','archivedGroups','subjects','bellProfiles','calendar','overrides','announcements','banners','teacherAssignments'],'School document');
  if pg_column_size(p_document) > 2000000 then raise exception 'Document exceeds 2 MB limit' using errcode='22023'; end if;
  perform school_private.assert_keys(p_document->'settings',array['anchorDate','anchorDay','timezone','regularDismissal'],'Settings');
  if p_document#>>'{settings,timezone}' is distinct from 'America/Belize' or
    coalesce(p_document#>>'{settings,anchorDay}','') !~ '^[1-7]$' or
    coalesce(p_document#>>'{settings,anchorDate}','') !~ '^\d{4}-\d{2}-\d{2}$' or
    coalesce(p_document#>>'{settings,regularDismissal}','') !~ '^([01]\d|2[0-3]):[0-5]\d$' then
    raise exception 'Settings require Belize timezone, valid anchor and dismissal time' using errcode='22023';
  end if;
  v_date := (p_document#>>'{settings,anchorDate}')::date;
  if extract(isodow from v_date) > 5 then raise exception 'Cycle anchor must be a weekday' using errcode='22023'; end if;
  if jsonb_typeof(p_document->'groups') is distinct from 'object' or p_document->'groups' = '{}'::jsonb or
    jsonb_typeof(p_document->'subjects') is distinct from 'object' then
    raise exception 'Groups and subjects are required objects' using errcode='22023';
  end if;
  if p_document ? 'archivedGroups' then
    if jsonb_typeof(p_document->'archivedGroups') is distinct from 'array' then raise exception 'Archived groups must be an array' using errcode='22023'; end if;
    if exists(select 1 from jsonb_array_elements(p_document->'archivedGroups') a where jsonb_typeof(a) is distinct from 'string' or not coalesce(p_document->'groups' ? (a#>>'{}'),false)) or
      (select count(*) <> count(distinct value) from jsonb_array_elements(p_document->'archivedGroups')) then
      raise exception 'Archived groups must be unique registered group codes' using errcode='22023';
    end if;
    if jsonb_array_length(p_document->'archivedGroups') >= (select count(*) from jsonb_object_keys(p_document->'groups')) then
      raise exception 'At least one active class must remain; cannot archive every group' using errcode='22023';
    end if;
  end if;
  for v_group in select key,value from jsonb_each(p_document->'subjects') loop
    perform school_private.assert_keys(v_group.value,array['name','icon'],'Subject');
    if coalesce(length(v_group.value->>'name'),0) not between 1 and 160 or coalesce(v_group.value->>'icon','') !~ '^[a-z0-9-]{1,60}$' then
      raise exception 'Subject needs name and icon slug' using errcode='22023';
    end if;
  end loop;
  for v_group in select key,value from jsonb_each(p_document->'groups') loop
    if v_group.key !~ '^[1-4][A-Z]{1,12}$' or jsonb_typeof(v_group.value) is distinct from 'array' or jsonb_array_length(v_group.value) <> 7 then
      raise exception 'Each valid group requires seven cycle days' using errcode='22023';
    end if;
    v_index := 0;
    for v_day in select value from jsonb_array_elements(v_group.value) loop
      v_index := v_index + 1; v_slots := 0;
      if jsonb_typeof(v_day) is distinct from 'array' or jsonb_array_length(v_day) = 0 then raise exception 'Each day needs lessons' using errcode='22023'; end if;
      for v_lesson in select value from jsonb_array_elements(v_day) loop
        perform school_private.assert_keys(v_lesson,array['subject','room','span'],'Lesson');
        if not coalesce(p_document->'subjects' ? (v_lesson->>'subject'),false) or not (v_lesson ? 'room') or
          jsonb_typeof(v_lesson->'room') not in ('string','null') or
          (v_lesson ? 'span' and coalesce(v_lesson->>'span','') !~ '^[12]$') then
          raise exception 'Lesson needs registered subject, room string/null and valid span' using errcode='22023';
        end if;
        v_span := coalesce((v_lesson->>'span')::integer,1); v_slots := v_slots + v_span;
      end loop;
      if (v_index = 7 and v_slots <> 4) or (v_index <> 7 and v_slots <> 6) then
        raise exception 'Days 1–6 require six session slots; Day 7 requires four student slots' using errcode='22023';
      end if;
    end loop;
  end loop;
  perform school_private.assert_keys(p_document->'bellProfiles',array['regular','quick','half'],'Bell profiles');
  if not (p_document->'bellProfiles' ?& array['regular','quick','half']) then raise exception 'All bell profiles required' using errcode='22023'; end if;
  for v_profile in select key,value from jsonb_each(p_document->'bellProfiles') loop
    perform school_private.assert_keys(v_profile.value,array['slots','dismissal'],'Bell profile');
    if jsonb_typeof(v_profile.value->'slots') is distinct from 'array' or
      jsonb_array_length(v_profile.value->'slots') <> (case when v_profile.key='half' then 4 else 6 end) or
      coalesce(v_profile.value->>'dismissal','') !~ '^([01]\d|2[0-3]):[0-5]\d$' then
      raise exception 'Invalid bell profile length or dismissal' using errcode='22023';
    end if;
    v_previous := '00:00';
    for v_slot in select value from jsonb_array_elements(v_profile.value->'slots') loop
      perform school_private.assert_keys(v_slot,array['start','end'],'Bell slot');
      if coalesce(v_slot->>'start','') !~ '^([01]\d|2[0-3]):[0-5]\d$' or coalesce(v_slot->>'end','') !~ '^([01]\d|2[0-3]):[0-5]\d$' or
        v_slot->>'start' < v_previous or v_slot->>'end' <= v_slot->>'start' then
        raise exception 'Bell slots must have valid ordered non-overlapping times' using errcode='22023';
      end if;
      v_previous := v_slot->>'end';
    end loop;
    if v_profile.value->>'dismissal' < v_previous then raise exception 'Dismissal precedes last lesson' using errcode='22023'; end if;
  end loop;
  if p_document#>>'{settings,regularDismissal}' <> p_document#>>'{bellProfiles,regular,dismissal}' then
    raise exception 'Regular dismissal settings and bell profile must match' using errcode='22023';
  end if;
  if jsonb_typeof(p_document->'calendar') is distinct from 'object' then raise exception 'Calendar must be an object' using errcode='22023'; end if;
  for v_calendar in select key,value from jsonb_each(p_document->'calendar') loop
    perform school_private.assert_keys(v_calendar.value,array['type','label','description','bellProfile'],'Calendar entry');
    if v_calendar.key !~ '^\d{4}-\d{2}-\d{2}$' or coalesce(v_calendar.value->>'type','') not in ('regular','holiday','async','event') or
      (v_calendar.value ? 'bellProfile' and coalesce(v_calendar.value->>'bellProfile','') not in ('regular','quick','half')) then
      raise exception 'Invalid calendar date, attendance type or bell profile' using errcode='22023';
    end if;
    perform v_calendar.key::date;
  end loop;
  if jsonb_typeof(p_document->'overrides') is distinct from 'array' or jsonb_typeof(p_document->'announcements') is distinct from 'array' or
    jsonb_typeof(p_document->'banners') is distinct from 'array' or jsonb_typeof(p_document->'teacherAssignments') is distinct from 'array' then
    raise exception 'Overrides, announcements, banners and assignments must be arrays' using errcode='22023';
  end if;
  for v_item in select value from jsonb_array_elements(p_document->'overrides') loop
    perform school_private.assert_keys(v_item,array['id','date','group','session','subject','room','teacher','note'],'Substitution');
    if coalesce(length(v_item->>'id'),0)=0 or not coalesce(p_document->'groups' ? (v_item->>'group'),false) or
      coalesce(v_item->>'date','') !~ '^\d{4}-\d{2}-\d{2}$' or coalesce(v_item->>'session','') !~ '^[1-6]$' or
      not coalesce(p_document->'subjects' ? (v_item->>'subject'),false) or not (v_item ? 'room') or jsonb_typeof(v_item->'room') not in ('string','null') then
      raise exception 'Invalid substitution identity, date, group, lesson or room' using errcode='22023';
    end if;
    perform (v_item->>'date')::date;
  end loop;
  for v_item in select value from jsonb_array_elements(p_document->'announcements') loop
    perform school_private.validate_notice(v_item,p_document->'groups');
  end loop;
  if (select count(*) <> count(distinct value->>'id') from jsonb_array_elements(p_document->'announcements')) then
    raise exception 'Duplicate notice IDs' using errcode='22023';
  end if;
  for v_item in select value from jsonb_array_elements(p_document->'banners') loop
    perform school_private.assert_keys(v_item,array['id','text','tone','startsAt','expiresAt'],'Banner');
    if coalesce(length(trim(v_item->>'text')),0) not between 1 and 500 or coalesce(v_item->>'tone','') not in ('info','warning','urgent') then
      raise exception 'Banner needs text and valid tone' using errcode='22023';
    end if;
    if v_item->>'startsAt' is not null then perform (v_item->>'startsAt')::timestamptz; end if;
    if v_item->>'expiresAt' is not null then perform (v_item->>'expiresAt')::timestamptz; end if;
  end loop;
  for v_item in select value from jsonb_array_elements(p_document->'teacherAssignments') loop
    perform school_private.assert_keys(v_item,array['teacher','group','day','session'],'Teacher assignment');
    if coalesce(length(v_item->>'teacher'),0) = 0 or not coalesce(p_document->'groups' ? (v_item->>'group'),false) or
      coalesce(v_item->>'day','') !~ '^[1-7]$' or coalesce(v_item->>'session','') !~ '^[1-6]$' then
      raise exception 'Invalid public teacher assignment' using errcode='22023';
    end if;
  end loop;
end; $$;
revoke all on function school_private.assert_keys(jsonb,text[],text), school_private.validate_notice(jsonb,jsonb), school_private.validate_school_document(jsonb) from public, anon, authenticated;

create or replace function public.get_my_school_membership()
returns jsonb language sql stable security definer set search_path = '' as $$
  select to_jsonb(m) from public.school_members m where m.user_id = auth.uid() and m.active;
$$;

create or replace function public.publish_school_document(p_document jsonb, p_expected_revision bigint)
returns table(revision bigint, document jsonb, published_at timestamptz)
language plpgsql security definer set search_path = '' as $$
declare
  v_member public.school_members; v_old jsonb; v_revision bigint; v_key text; v_group text; v_item jsonb; v_capability text;
begin
  select * into v_member from public.school_members m where m.user_id = auth.uid() and m.active;
  if v_member.user_id is null or v_member.role = 'teacher' then raise exception 'Publishing permission required' using errcode='42501'; end if;
  perform pg_advisory_xact_lock(742617092);
  select s.document,s.revision into v_old,v_revision from public.school_versions s order by s.revision desc limit 1;
  if p_expected_revision is distinct from coalesce(v_revision,0) then raise exception 'Revision conflict: reload latest schedule before publishing' using errcode='40001'; end if;
  perform school_private.validate_school_document(p_document);
  foreach v_key in array array['settings','groups','archivedGroups','subjects','bellProfiles','calendar','overrides','announcements','banners','teacherAssignments'] loop
    if p_document->v_key is distinct from v_old->v_key then
      v_capability := case v_key when 'archivedGroups' then 'classes.manage' when 'subjects' then 'subjects.manage' when 'calendar' then 'calendar.manage' when 'bellProfiles' then 'calendar.manage'
        when 'overrides' then 'substitutions.manage' when 'announcements' then 'notices.publish' when 'banners' then 'banners.manage' else 'schedules.manage' end;
      if not school_private.has_capability(v_capability) then raise exception 'Missing capability: %',v_capability using errcode='42501'; end if;
      if v_member.role = 'codeveloper' and not ('*' = any(v_member.groups)) then
        if v_key in ('settings','subjects','bellProfiles','calendar','banners','teacherAssignments') then raise exception 'Schoolwide scope required for %',v_key using errcode='42501'; end if;
        if v_key = 'archivedGroups' then
          for v_group in select value from jsonb_array_elements_text(coalesce(v_old->'archivedGroups','[]')) union select value from jsonb_array_elements_text(p_document->'archivedGroups') loop
            if not (coalesce(v_old->'archivedGroups','[]') ? v_group and p_document->'archivedGroups' ? v_group) and not school_private.in_scope(v_group) then
              raise exception 'Archived group outside assigned scope' using errcode='42501';
            end if;
          end loop;
        elsif v_key = 'groups' then
          for v_group in select key from jsonb_object_keys(coalesce(v_old->'groups','{}') || p_document->'groups') key loop
            if p_document->'groups'->v_group is distinct from v_old->'groups'->v_group and not school_private.in_scope(v_group) then raise exception 'Group outside assigned scope' using errcode='42501'; end if;
          end loop;
        else
          for v_item in select value from jsonb_array_elements(coalesce(v_old->v_key,'[]')) union select value from jsonb_array_elements(p_document->v_key) loop
            if not (coalesce(v_old->v_key,'[]') @> jsonb_build_array(v_item) and p_document->v_key @> jsonb_build_array(v_item)) and
              not school_private.in_scope(case when v_key='announcements' then v_item->>'audience' else v_item->>'group' end) then
              raise exception 'Changed item outside assigned scope' using errcode='42501';
            end if;
          end loop;
        end if;
      end if;
    end if;
  end loop;
  if (select array_agg(key order by key) from jsonb_object_keys(p_document->'groups') key) is distinct from
    (select array_agg(key order by key) from jsonb_object_keys(coalesce(v_old->'groups','{}')) key) and not school_private.has_capability('classes.manage') then
    raise exception 'Creating or archiving classes requires classes.manage' using errcode='42501';
  end if;
  insert into public.school_versions(document,published_by) values(p_document,auth.uid());
  insert into public.school_audit_events(actor,action,details) values(auth.uid(),'school.publish',jsonb_build_object('previousRevision',coalesce(v_revision,0)));
  return query select s.revision,s.document,s.published_at from public.school_versions s order by s.revision desc limit 1;
end; $$;

create or replace function public.submit_school_notice(p_notice jsonb)
returns uuid language plpgsql security definer set search_path = '' as $$
declare v_document jsonb; v_notice jsonb; v_id uuid := gen_random_uuid();
begin
  if auth.uid() is null or not school_private.has_capability('notices.submit') or not school_private.in_scope(p_notice->>'audience') then
    raise exception 'Notice submission requires assigned audience permission' using errcode='42501';
  end if;
  select s.document into v_document from public.school_versions s order by s.revision desc limit 1;
  v_notice := p_notice || jsonb_build_object('id',v_id::text,'approved',true,'publishedAt',now());
  perform school_private.validate_notice(v_notice,v_document->'groups');
  insert into public.school_notice_drafts(id,submitted_by,notice) values(v_id,auth.uid(),v_notice);
  insert into public.school_audit_events(actor,action,details) values(auth.uid(),'notice.submit',jsonb_build_object('id',v_id));
  return v_id;
end; $$;

create or replace function public.approve_school_notice(p_id uuid,p_expected_revision bigint)
returns table(revision bigint,document jsonb,published_at timestamptz)
language plpgsql security definer set search_path = '' as $$
declare v_draft public.school_notice_drafts; v_document jsonb;
begin
  if not school_private.has_capability('notices.publish') then raise exception 'Notice review permission required' using errcode='42501'; end if;
  select * into v_draft from public.school_notice_drafts n where n.id=p_id for update;
  if v_draft.id is null or v_draft.status<>'pending' or not school_private.in_scope(v_draft.notice->>'audience') then raise exception 'Pending notice not found in assigned scope' using errcode='42501'; end if;
  select s.document into v_document from public.school_versions s order by s.revision desc limit 1;
  v_document := jsonb_set(v_document,'{announcements}',(v_document->'announcements') || jsonb_build_array(v_draft.notice || jsonb_build_object('publishedAt',now())));
  return query select * from public.publish_school_document(v_document,p_expected_revision);
  update public.school_notice_drafts set status='approved',reviewed_at=now(),reviewed_by=auth.uid() where id=p_id;
end; $$;

create or replace function public.set_school_member(p_user_id uuid,p_role text,p_capabilities text[],p_groups text[],p_active boolean)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_actor public.school_members; v_result jsonb; v_groups jsonb;
begin
  select * into v_actor from public.school_members m where m.user_id=auth.uid() and m.active;
  if v_actor.role is distinct from 'developer' then raise exception 'Only Developer can grant or change membership' using errcode='42501'; end if;
  if p_user_id=auth.uid() then raise exception 'Developer cannot change their own membership through this API' using errcode='42501'; end if;
  if p_role not in ('developer','principal','teacher','codeveloper') or p_capabilities is null or p_groups is null or p_active is null or
    not p_capabilities <@ array['schedules.manage','classes.manage','subjects.manage','calendar.manage','substitutions.manage','notices.submit','notices.publish','banners.manage']::text[] then
    raise exception 'Invalid role or capability' using errcode='22023';
  end if;
  if p_role='teacher' and not p_capabilities <@ array['notices.submit']::text[] then raise exception 'Teacher grants are limited to notice submissions' using errcode='22023'; end if;
  select s.document->'groups' into v_groups from public.school_versions s order by s.revision desc limit 1;
  if exists(select 1 from unnest(p_groups) g where g is null or (g<>'*' and not (v_groups ? g))) or ('*'=any(p_groups) and p_role='teacher') then
    raise exception 'Invalid group scope' using errcode='22023';
  end if;
  insert into public.school_members(user_id,role,capabilities,groups,active) values(p_user_id,p_role,p_capabilities,p_groups,p_active)
    on conflict(user_id) do update set role=excluded.role,capabilities=excluded.capabilities,groups=excluded.groups,active=excluded.active,updated_at=now()
    returning to_jsonb(school_members.*) into v_result;
  insert into public.school_audit_events(actor,action,details) values(auth.uid(),'member.change',jsonb_build_object('userId',p_user_id,'role',p_role,'capabilities',p_capabilities,'groups',p_groups,'active',p_active));
  return v_result;
end; $$;

revoke all on function public.get_my_school_membership(), public.publish_school_document(jsonb,bigint), public.submit_school_notice(jsonb), public.approve_school_notice(uuid,bigint), public.set_school_member(uuid,text,text[],text[],boolean) from public, anon, authenticated;
grant execute on function public.get_my_school_membership(), public.publish_school_document(jsonb,bigint), public.submit_school_notice(jsonb), public.approve_school_notice(uuid,bigint), public.set_school_member(uuid,text,text[],text[],boolean) to authenticated;
commit;
